; ============================================================
; Лабораторная работа №4 - Вариант 1 (шифр 1а)
; Задача:
; 1) Заменить прерывание 1CH, которое выполняется n раз
; 2) После n вызовов - преобразовать строку и восстановить прерывание
; 3) Преобразование: найти все позиции символа 'D' в строке
; ============================================================

.model small
.stack 1024                    ; 1 Кбайт под стек

.data
    ; Константы
    EOFLine EQU '$'            ; Символ конца строки

    ; Сохранение старого вектора прерывания 1CH
    KEEP_IP DW 0               ; Здесь сохраним смещение старого обработчика
    KEEP_CS DW 0               ; Здесь сохраним сегмент старого обработчика

    ; Переменные для работы прерывания 1CH
    TIMER_COUNT DW 0           ; Счётчик вызова прерывания 1CH
    MAX_COUNT DW 7             ; Сколько раз должно вызваться
    WORK_DONE DB 0             ; Флаг: 0=работа не выполнена, 1=выполнена

    ; Строки для ввода/вывода
    STR1HEAD DB 50h, 0         ; Заголовок для ввода
    STR1 DB 80 DUP('*'), 0AH, 0DH, EOFLine  ; Буфер для ввода
    STR2 DB 300 DUP(' '), 0AH, 0DH, EOFLine  ; Буфер для результата

    ; Сообщения
    MSG_WELCOME DB 'Лабораторная работа 4. Вариант 1. Выполнил ст. гр. 4344 Байдаков Георгий', 0AH, 0DH
                DB 'Введите строку:', 0AH, 0DH, EOFLine

    MSG_WAIT DB 0AH, 0DH, 'Ожидание ввода... (нажмите Enter)', 0AH, 0DH, EOFLine

    MSG_RESULT DB 0AH, 0DH, 'Позиции символа D: ', EOFLine

    MSG_NO_WORK DB 0AH, 0DH, 'Работа не выполнена (завершили слишком быстро)', 0AH, 0DH, EOFLine

    MSG_NO_D DB 'В строке не найдено символов D', 0AH, EOFLine

.code
start:
    mov ax, @data
    mov ds, ax
    mov es, ax

    ; ============================================================
    ; ПУНКТ 1. Вывод приветствия и ввод строки
    ; ============================================================

    mov dx, OFFSET MSG_WELCOME ; Адрес приветственного сообщения
    call PrintString           ; Вывод приветствия

    mov dx, OFFSET STR1HEAD    ; Адрес заголовка строки
    call StringRead            ; Вызов процедуры ввода

    ; ============================================================
    ; Определение n (MAX_COUNT) на основе первого символа
    ; Если первый символ - цифра x, то n = 10 * x, иначе n = 7
    ; ============================================================

    xor bx, bx
    mov bl, ds:[STR1HEAD+1]    ; Количество реально введённых символов
    cmp bl, 0                  ; Если строка пустая
    je set_default_n           ; то n = 7

    mov al, STR1[0]            ; Первый символ строки
    cmp al, '0'                ; Проверка: это цифра?
    jb set_default_n           ; Если меньше '0' - не цифра
    cmp al, '9'
    ja set_default_n           ; Если больше '9' - не цифра

    ; Первый символ - цифра. Вычисление n = 10 * x
    sub al, '0'                ; ASCII код в число (например)
    xor ah, ah                 ; AH = 0, теперь AX = x
    mov cl, 10
    mul cl                     ; AX = x * 10
    mov MAX_COUNT, ax          ; Сохранение результата
    jmp save_old_1ch

set_default_n:
    mov MAX_COUNT, 7           ; n = 7 по умолчанию

    ; ============================================================
    ; Пункт 2. Сохранение и замена прерывания 1CH
    ; ============================================================
save_old_1ch:
    ; Получение текущего вектора прерывания 1CH
    mov ah, 35h
    mov al, 1Ch                ; Номер вектора
    int 21h                    ; 
    mov KEEP_IP, bx            ; Сохранение смещения
    mov KEEP_CS, es            ; Сохранение сегмента

    ; Устанавливаем собственный обработчик 1CH
    push ds                    ; Сохранение DS
    mov dx, OFFSET INT_1CH_HANDLER  ; DX = смещение нашей процедуры
    mov ax, SEG INT_1CH_HANDLER     ; AX = сегмент нашей процедуры
    mov ds, ax                 ; Сегмент в DS
    mov ah, 25h                ; Функция 25h - установить вектор
    mov al, 1Ch                ; Номер вектора
    int 21h                    ; Теперь 1CH указывает на INT_1CH_HANDLER
    pop ds                     ; Восстановление DS

    ; ============================================================
    ; Пункт 3. Ожидание ввода строки (задержка с возможностью нажатия клавиш)
    ; ============================================================

    mov dx, OFFSET MSG_WAIT
    call PrintString

    ; Ожидание нажатия Enter (можно нажимать разные клавиши)
    mov dx, OFFSET STR1HEAD
    call StringRead


    ; ============================================================
    ; Проверка. Выполнена ли работа?
    ; ============================================================

    cmp WORK_DONE, 1           ; Проверка флага
    je work_was_done           ; Если работа выполнена

    ; Работа не выполнена (пользователь завершил слишком быстро)
    mov dx, OFFSET MSG_NO_WORK
    call PrintString
    jmp restore_and_exit

work_was_done:
    ; Работа уже выполнена прерыванием 1CH - ничего делать не нужно

    ; ============================================================
    ; Восстановление прерывания 1CH и завершение программы
    ; ============================================================
restore_and_exit:
    ; Восстановление старого вектора 1CH
    push ds
    mov dx, KEEP_IP            ; Загрузка сохранённого смещения
    mov ax, KEEP_CS            ; Загрузка сохранённого сегмента
    mov ds, ax                 ; Помещаем в DS
    mov ah, 25h                ; Функция установки вектора
    mov al, 1Ch                ; Номер вектора
    int 21h                    ; Восстановление
    pop ds

    ; Завершение программы
    mov ax, 4C00h              ; Функция 4Ch - завершение программы
    int 21h                    ; Возврат

; ============================================================
; Обработчик прерывания 1CH (вызывается примерно 18.2 раза в секунду)
; ============================================================
INT_1CH_HANDLER PROC FAR
    ; Загружаем сегмент данных (в прерывании DS может быть любым)
    mov ax, @data
    mov ds, ax
    mov es, ax

    ; Провекра: уже выполнил работу?
    cmp WORK_DONE, 1
    je exit_handler            ; Если выполнил, то выходим

    ; Увеличиваем счётчик вызовов
    inc TIMER_COUNT
    mov ax, TIMER_COUNT
    cmp ax, MAX_COUNT          ; Достигли нужного кол-ва вызовов?
    jb exit_handler            ; Если нет, то выходим

    ; Достигли n вызовов - выполняем работу
    call DoWork                ; Преобразование строки и вывод результата

    ; Восстановление вектора 1Ch на старый обработчик
    push ds
    mov dx, KEEP_IP
    mov ax, KEEP_CS
    mov ds, ax
    mov ah, 25h
    mov al, 1Ch
    int 21h
    pop ds

    mov WORK_DONE, 1           ; Работа выполнена

exit_handler:
    iret                       ; Возврат из прерывания
INT_1CH_HANDLER ENDP

; ============================================================
; Процедура DoWork - выполнение преобразования строки
; Находит все позиции символа 'D'
; ============================================================
DoWork PROC NEAR
    lea di, STR2
    mov cx, 300
    mov al, ' '
    rep stosb                  ; Заполнение пробелами

    ; Подготовка к поиску
    lea si, STR1               ; SI указывает на входную строку
    lea di, STR2               ; DI указывает на выходную строку
    xor bx, bx                 ; Начинаем с индекса 0
    mov cl, ds:[STR1HEAD+1]    ; CL = длина строки
    xor ch, ch                 ; CX = длина строки
    cmp cx, 0
    je no_d_found              ; Если строка пустая => d не найдено

    xor dx, dx                 ; DX = счётчик найденных 'D'

search_loop:
    lodsb                      ; Загружает байт из DS:SI в AL, SI++
    cmp al, 'D'                ; Это символ 'D'?
    je found_d                 ; Если да, то обрабатываем

continue_search:
    inc bx                     ; Увеличиваем счётчик позиции
    loop search_loop           ; Продолжаем поиск

    ; Поиск завершён
    cmp dx, 0                  ; Нашли хотя бы одну 'D'?
    je no_d_found              ; Если нет

    ; Завершаем выходную строку
    mov byte ptr [di], 0Ah
    mov byte ptr [di+1], 0Dh
    mov byte ptr [di+2], EOFLine

    ; Выводим результат
    mov dx, OFFSET MSG_RESULT
    call PrintString
    mov dx, OFFSET STR2
    call PrintString
    jmp end_dowork

found_d:
    ; Найден символ 'D' на позиции BX
    inc dx                     ; Увеличиваем счётчик найденных

    ; Преобразуем номер позиции в строку
    push cx
    push bx
    inc bx                     ; Позиции нумеруются с 1
    mov ax, bx                 ; Число для преобразования
    call NumberToString        ; Преобразуем и записываем в [DI]

    ; Добавляем пробел после числа
    mov byte ptr [di], ' '
    inc di

    pop bx
    pop cx
    jmp continue_search

no_d_found:
    mov dx, OFFSET MSG_NO_D
    call PrintString

end_dowork:
    ret

DoWork ENDP

; ============================================================
; Процедура NumberToString
; Вход: AX = число, ES:DI = куда записывать строку
; Выход: DI указывает на байт после последней цифры
; ============================================================
NumberToString PROC NEAR
    mov cx, 0                  ; Счётчик цифр
    mov bx, 10                 ; Делитель

    ; Если число = 0
    cmp ax, 0
    jne convert_loop
    mov byte ptr [di], '0'
    inc di
    jmp end_convert

convert_loop:
    ; Делим AX на 10, остаток в DX - очередная цифра
    xor dx, dx
    div bx                     ; AX = AX / 10, DX = AX % 10
    push dx                    ; Сохраняем цифру в стеке
    inc cx                     ; Увеличиваем счётчик
    cmp ax, 0                  ; Проверка: Есть ли еще цифра?
    jne convert_loop

    ; Извлекаем цифры из стека
write_digits:
    pop dx
    add dl, '0'                ; Преобразование в ASCII
    mov byte ptr [di], dl
    inc di
    loop write_digits

end_convert:
    ret
NumberToString ENDP

PrintString PROC NEAR
    push ax
    mov ah, 09h
    int 21h
    pop ax
    ret
PrintString ENDP

StringRead PROC NEAR
    mov ah, 0Ah                ; Функция - ввод строки
    push dx                    ; Сохраняем DX
    int 21h                    ; Вызов функции
    pop bp                     ; BP = адрес заголовка

    ; Добавляем завершающие байты
    xor bx, bx                 ; Обнуляем регистр bx
    mov bl, ds:[bp+1]          ; В bl теперь количество считанных символов
    add bx, bp                 ;
    add bx, 2                  ; Теперь указывает на последний символ 0Dh
    mov word ptr [bx+1], 240Ah   ; Заменяем последний символ на два: '\n' и '$'
    ret
StringRead ENDP

end start
