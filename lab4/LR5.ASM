;===============================================================================
; Лабораторная работа №4 - Вариант 1а
; Задача: 
; 1) Заменить прерывание 1CH (таймер), которое выполнится n раз
; 2) После n вызовов - преобразовать строку и восстановить прерывание
; 3) Преобразование: найти все позиции символа 'D' в строке
;===============================================================================

.model small
.stack 1024                    ; 1 Кбайт под стек (рекомендация из задания)

.data
    ; ===== Константы =====
    EOFLine EQU '$'            ; Символ конца строки для функции 09h DOS
    
    ; ===== Сохранение старого вектора прерывания 1CH =====
    KEEP_IP DW 0               ; Здесь сохраним смещение (offset) старого обработчика
    KEEP_CS DW 0               ; Здесь сохраним сегмент старого обработчика
    
    ; ===== Переменные для работы прерывания 1CH =====
    TIMER_COUNT DW 0           ; Счётчик: сколько раз уже вызвалось прерывание 1CH
    MAX_COUNT DW 7             ; Сколько раз должно вызваться (n из задания)
    WORK_DONE DB 0             ; Флаг: 0=работа не выполнена, 1=выполнена
    
    ; ===== Строки для ввода/вывода =====
    STR1HEAD DB 50h, 0         ; Заголовок для ввода: max 80 (50h) символов
                               ; Второй байт заполнит DOS (фактическое кол-во)
    STR1 DB 80 DUP('*'), 0AH, 0DH, EOFLine  ; Буфер для ввода + завершители
    
    STR2 DB 300 DUP(' '), 0AH, 0DH, EOFLine  ; Буфер для результата
    
    ; ===== Сообщения =====
    MSG_WELCOME DB 'Lab 4. Variant 1a', 0AH
                DB 'Vvedite stroku:', 0AH, EOFLine
    
    MSG_WAIT DB 0AH, 0DH, 'Ozhidanie vvoda... (nazhmite Enter)', 0AH, 0DH, EOFLine
    
    MSG_RESULT DB 0AH, 0DH, 'Pozicii simvola D: ', EOFLine
    
    MSG_NO_WORK DB 0AH, 0DH, 'Rabota ne vypolnena (zavershili slishkom bystro)', 0AH, 0DH, EOFLine

    MSG_NO_D DB 0AH, 0DH, 'NO D', 0AH, 0DH, EOFLine

.code
start:
    mov ax, @data
    mov ds, ax
    mov es, ax                 ; ES тоже инициализируем (нужен для строковых команд)
    
    ;===========================================================================
    ; ПУНКТ 1: Вывод приветствия и ввод строки
    ;===========================================================================
    
    mov dx, OFFSET MSG_WELCOME
    call PrintString           ; Выводим приветствие
    
    mov dx, OFFSET STR1HEAD    ; Адрес заголовка строки
    call StringRead            ; Вызываем процедуру ввода
    
    ;===========================================================================
    ; Определение n (MAX_COUNT) на основе первого символа
    ; Если первый символ - цифра x, то n = 10*x, иначе n = 7
    ;===========================================================================
    
    xor bx, bx
    mov bl, ds:[STR1HEAD+1]    ; Количество реально введённых символов
    cmp bl, 0                  ; Если строка пустая
    je set_default_n           ; То n = 7
    
    mov al, STR1[0]            ; Берём первый символ строки
    cmp al, '0'                ; Проверяем: это цифра?
    jb set_default_n           ; Если меньше '0' - не цифра
    cmp al, '9'
    ja set_default_n           ; Если больше '9' - не цифра
    
    ; Первый символ - цифра! Вычисляем n = 10 * x
    sub al, '0'                ; Преобразуем ASCII код в число (например, '5' -> 5)
    xor ah, ah                 ; AH = 0, теперь AX = x
    mov cl, 10
    mul cl                     ; AX = AL * 10
    mov MAX_COUNT, ax          ; Сохраняем результат
    jmp save_old_1ch
    
set_default_n:
    mov MAX_COUNT, 7           ; n = 7 по умолчанию
    
    ;===========================================================================
    ; ПУНКТ 2: Сохранение и замена прерывания 1CH
    ;===========================================================================
save_old_1ch:
    ; Получаем текущий вектор прерывания 1CH
    mov ah, 35h                ; Функция 35h прерывания 21h - получить вектор
    mov al, 1Ch                ; Номер вектора (1CH - таймер)
    int 21h                    ; После вызова: ES:BX = адрес обработчика
    mov KEEP_IP, bx            ; Сохраняем смещение
    mov KEEP_CS, es            ; Сохраняем сегмент
    
    ; Устанавливаем свой обработчик 1CH
    push ds                    ; Сохраняем DS (функция 25h портит его)
    mov dx, OFFSET INT_1CH_HANDLER  ; DX = смещение нашей процедуры
    mov ax, SEG INT_1CH_HANDLER     ; AX = сегмент нашей процедуры
    mov ds, ax                 ; Помещаем сегмент в DS
    mov ah, 25h                ; Функция 25h - установить вектор
    mov al, 1Ch                ; Номер вектора
    int 21h                    ; Теперь 1CH указывает на INT_1CH_HANDLER
    pop ds                     ; Восстанавливаем DS
    
    ;===========================================================================
    ; ПУНКТ 3: Ожидание ввода строки (просто задержка с возможностью нажатия клавиш)
    ;===========================================================================
    
    mov dx, OFFSET MSG_WAIT
    call PrintString
    
    ; Ожидаем нажатие Enter (можно нажимать разные клавиши)
    mov dx, OFFSET STR1HEAD
    call StringRead
    
    ;===========================================================================
    ; Проверка: выполнена ли работа?
    ;===========================================================================
    
    cmp WORK_DONE, 1           ; Проверяем флаг
    je work_was_done           ; Если 1 - работа выполнена
    
    ; Работа не выполнена (пользователь завершил слишком быстро)
    mov dx, OFFSET MSG_NO_WORK
    call PrintString
    jmp restore_and_exit
    
work_was_done:
    ; Работа уже выполнена прерыванием 1CH - ничего делать не нужно
    
    ;===========================================================================
    ; Восстановление прерывания 1CH и завершение программы
    ;===========================================================================
restore_and_exit:
    ; Восстанавливаем старый вектор 1CH
    push ds
    mov dx, KEEP_IP            ; Загружаем сохранённое смещение
    mov ax, KEEP_CS            ; Загружаем сохранённый сегмент
    mov ds, ax                 ; Помещаем в DS
    mov ah, 25h                ; Функция установки вектора
    mov al, 1Ch                ; Номер вектора
    int 21h                    ; Восстанавливаем
    pop ds
    
    ; Завершение программы
    mov ax, 4C00h              ; Функция 4Ch - завершение программы
    int 21h                    ; Возврат в DOS

;===============================================================================
; Обработчик прерывания 1CH (вызывается таймером ~18.2 раза в секунду)
;===============================================================================
INT_1CH_HANDLER PROC FAR
    push ax
    push bx
    push cx
    push dx
    push si
    push di
    push ds
    push es
    
    ; Загружаем сегмент данных (в прерывании DS может быть любым!)
    mov ax, @data
    mov ds, ax
    mov es, ax
    
    ; Проверяем: уже выполнили работу?
    cmp WORK_DONE, 1
    je exit_handler            ; Если да - просто выходим
    
    ; Увеличиваем счётчик вызовов
    inc TIMER_COUNT
    mov ax, TIMER_COUNT
    cmp ax, MAX_COUNT          ; Достигли нужного количества вызовов?
    jb exit_handler            ; Если нет - выходим
    
    ; Достигли n вызовов - выполняем работу!
    call DoWork                ; Преобразуем строку и выводим результат
    
    ; Восстанавливаем вектор 1CH на старый обработчик
    push ds
    mov dx, KEEP_IP
    mov ax, KEEP_CS
    mov ds, ax
    mov ah, 25h
    mov al, 1Ch
    int 21h
    pop ds
    
    mov WORK_DONE, 1           ; Отмечаем, что работа выполнена
    
exit_handler:
    pop es
    pop ds
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    pop ax
    iret                       ; Возврат из прерывания
INT_1CH_HANDLER ENDP

;===============================================================================
; Процедура DoWork - выполнение основной работы
; Преобразует строку: находит все позиции символа 'D'
;===============================================================================
DoWork PROC NEAR
    push ax
    push bx
    push cx
    push dx
    push si
    push di
    
    ; Очистка выходного буфера
    lea di, STR2
    mov cx, 300
    mov al, ' '
    rep stosb                  ; Заполняем пробелами
    
    ; Подготовка к поиску
    lea si, STR1               ; SI указывает на входную строку
    lea di, STR2               ; DI указывает на выходную строку
    xor bx, bx                 ; BX = текущая позиция в строке (начинаем с 0)
    mov cl, ds:[STR1HEAD+1]    ; CL = длина строки
    xor ch, ch                 ; CX = длина строки
    cmp cx, 0
    je no_d_found              ; Если строка пустая
    
    xor dx, dx                 ; DX = счётчик найденных 'D'
    
search_loop:
    lodsb                      ; Загружаем байт из DS:SI в AL, SI++
    cmp al, 'D'                ; Это символ 'D'?
    je found_d                 ; Если да - обрабатываем
    cmp al, 'd'                ; Может быть, маленькая 'd'?
    je found_d
    
continue_search:
    inc bx                     ; Увеличиваем номер позиции
    loop search_loop           ; Продолжаем поиск
    
    ; Поиск завершён
    cmp dx, 0                  ; Нашли хотя бы одну 'D'?
    je no_d_found              ; Если нет
    
    ; Завершаем выходную строку
    mov byte ptr [di], 0Ah
    mov byte ptr [di+1], 0Dh
    mov byte ptr [di+2], '$'
    
    ; Выводим результат
    mov dx, OFFSET MSG_RESULT
    call PrintString
    mov dx, OFFSET STR2
    call PrintString
    jmp end_dowork
    
found_d:
    ; Найден символ 'D' на позиции BX
    inc dx                     ; Увеличиваем счётчик найденных
    
    ; Преобразуем номер позиции (BX+1) в строку
    push cx
    push bx
    inc bx                     ; Позиции нумеруются с 1, а не с 0
    mov ax, bx                 ; Число для преобразования
    call NumberToString        ; Преобразуем и записываем в [DI]
    
    ; Добавляем пробел после числа
    mov byte ptr [di], ' '
    inc di
    
    pop bx
    pop cx
    jmp continue_search
    
no_d_found:
    mov dx, OFFSET MSG_NO_D
    call PrintString
    
end_dowork:
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    pop ax
    ret
DoWork ENDP

;===============================================================================
; Процедура NumberToString
; Вход: AX = число, ES:DI = куда записать строку
; Выход: DI указывает на байт после последней цифры
;===============================================================================
NumberToString PROC NEAR
    push ax
    push bx
    push cx
    push dx
    
    mov cx, 0                  ; Счётчик цифр
    mov bx, 10                 ; Делитель
    
    ; Особый случай: число = 0
    cmp ax, 0
    jne convert_loop
    mov byte ptr [di], '0'
    inc di
    jmp end_convert
    
convert_loop:
    ; Делим AX на 10, остаток в DX - это очередная цифра
    xor dx, dx
    div bx                     ; AX = AX / 10, DX = AX % 10
    push dx                    ; Сохраняем цифру в стеке
    inc cx                     ; Увеличиваем счётчик цифр
    cmp ax, 0                  ; Ещё есть цифры?
    jne convert_loop
    
    ; Извлекаем цифры из стека (они там в обратном порядке)
write_digits:
    pop dx
    add dl, '0'                ; Преобразуем в ASCII
    mov byte ptr [di], dl
    inc di
    loop write_digits
    
end_convert:
    pop dx
    pop cx
    pop bx
    pop ax
    ret
NumberToString ENDP

;===============================================================================
; Процедура StringRead - ввод строки с клавиатуры
; Вход: DX = адрес заголовка строки (STR1HEAD)
;===============================================================================
StringRead PROC NEAR
    push ax
    push bx
    push bp
    push dx
    
    mov ah, 0Ah                ; Функция 0Ah - ввод строки
    push dx                    ; Сохраняем DX
    int 21h                    ; Вызов DOS
    pop bp                     ; BP = адрес заголовка
    
    ; Добавляем завершающие байты в конец строки
    xor bx, bx
    mov bl, ds:[bp+1]          ; Количество введённых символов
    add bx, bp                 ; BX указывает на последний символ
    add bx, 2                  ; BX указывает за 0Dh
    mov word ptr [bx+1], 240Ah ; Добавляем 0Ah и '$'
    
    pop dx
    pop bp
    pop bx
    pop ax
    ret
StringRead ENDP

;===============================================================================
; Процедура PrintString - вывод строки на экран
; Вход: DX = адрес строки (завершается символом '$')
;===============================================================================
PrintString PROC NEAR
    push ax
    mov ah, 09h                ; Функция 09h - вывод строки
    int 21h
    pop ax
    ret
PrintString ENDP

end start
